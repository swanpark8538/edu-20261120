CREATE TABLE BOARD (
  BOARD_ID     VARCHAR(20) NOT NULL,
  TITLE        VARCHAR(200) NOT NULL,
  CONTENT      VARCHAR(4000),
  WRITER       VARCHAR(50) NOT NULL,
  ATCH_FILE_ID VARCHAR(20),
  REG_DT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
