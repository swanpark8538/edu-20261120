CREATE TABLE BOARD (
 BOARD_ID VARCHAR(20) NOT NULL PRIMARY KEY,
 TITLE VARCHAR(200) NOT NULL,
 CONTENT VARCHAR(4000),
 WRITER VARCHAR(50) NOT NULL,
 ATCH_FILE_ID VARCHAR(36) NOT NULL UNIQUE,
 CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE BOARD_FILE (
 FILE_ID VARCHAR(36) PRIMARY KEY,
 BOARD_ID VARCHAR(20) NOT NULL REFERENCES BOARD(BOARD_ID) ON DELETE CASCADE,
 ORIGINAL_NAME VARCHAR(200) NOT NULL,
 STORED_NAME VARCHAR(36) NOT NULL,
 FILE_SIZE BIGINT NOT NULL
);
CREATE TABLE IDS (TABLE_NAME VARCHAR(20) PRIMARY KEY, NEXT_ID BIGINT NOT NULL);
